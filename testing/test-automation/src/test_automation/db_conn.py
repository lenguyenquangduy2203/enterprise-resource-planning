from typing import Any, List, Optional, Protocol, Tuple, Union

from mysql.connector.abstracts import MySQLConnectionAbstract
from mysql.connector.pooling import PooledMySQLConnection


class CursorLike(Protocol):
    """Minimal protocol for a DB cursor used by test helpers."""

    rowcount: int

    def execute(self, operation: str, params: Tuple[Any, ...] = ()) -> None: ...
    def fetchone(self) -> Optional[Tuple[Any, ...]]: ...
    def fetchall(self) -> List[Tuple[Any, ...]]: ...
    def close(self) -> bool: ...


class DBConnectionLike(Protocol):
    """Protocol representing a MySQL connection returned by mysql.connector.connect."""

    def is_connected(self) -> bool: ...
    def cursor(self, dictionary: bool = False) -> CursorLike: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...


MySQLConnType = Union[PooledMySQLConnection, MySQLConnectionAbstract, DBConnectionLike]
